#pragma once

#include <memory>
#include <random>
#include "car.hpp"

/**
 * @brief Abstract Car Factory class. This class outlines the interface of all Car Factories that will create cars with 
 * different following models.
 * 
 */
class CarFactory {

protected: 
    std::normal_distribution<double> politeness_dist_; ///< Distribution of politeness values for the cars
    mutable size_t carid_; ///< Car id of the next car to be generated

public:
    
    /**
     * @brief Construct a new Car Factory object with a mean politeness and politeness standard deviation. 
     * 
     * @param politeness Mean politeness value of all cars generated by the factory
     * @param p_stdev Standard deviation of the politeness of all cars generated. 
     */
    CarFactory(double politeness, double p_stdev);
    virtual ~CarFactory() = default;

    /**
     * @brief Generates a car from this factory. The car's position, velocities and timestamp are the arguments
     * to this function, the politeness comes from the politeness data member variables and the follow
     * model comes from the data in the derived classes. 
     * 
     * @param x0 Initial position of the car.
     * @param v0 Initial car velocity
     * @param vdes Desired velocity of the car
     * @param t0 (optional) The initial timestamp of the car
     * @return Car with specified attributtes and a follow model generated by rng
     */
    virtual Car makeCar(double x0, double v0, double vdes, double t0 = 0) = 0;

    /**
     * @brief Builds a car from ALL the necessary car data to construct the car -- no randomness necessary. 
     * @note Does not increment the car_id counter since the car id is supplied by the car 
     * 
     * @param id Car ID of the car. 
     * @param x0 Initial position of the car.
     * @param v0 Initial car velocity
     * @param vdes Desired velocity of the car
     * @param t0 Initial timestamp of the car
     * @param a Follow model A parameter
     * @param b Follow Model B parameter
     * @param c Follow model C parameter
     * @param p Lane changing politeness
     * @return Car with specified attributes
     */
    virtual Car makeCar(size_t id, double x0, double v0, double vdes, double t0, double a, double b, double c, double p) = 0;

    /**
     * @brief Set the carID field. This is used for checkpointed starts where the carID needs to get set
     * to the id of the next new car. Required to get matching results between full runs and checkpointed runs
     * 
     * @param id Id of the next car generated
     */
    void setCarID (size_t id) {carid_ = id;}};


template <typename F>
class CarFactoryImpl : public CarFactory {
    std::mt19937 rng_;
    std::normal_distribution<double> a_dist;
    std::normal_distribution<double> b_dist;
    std::normal_distribution<double> c_dist;
    F makeFollowModel_;

    public: 
    CarFactoryImpl(double a, double b, double c, double p,
                    double a_stdev , double b_stdev , double c_stdev, double p_stdev,
                    size_t seed,  F func);

    ~CarFactoryImpl() = default;

    Car makeCar(double x0, double v0, double vdes, double t0) override;
    Car makeCar(size_t id, double x0, double v0, double vdes, double t0, double a, double b, double c, double p) override;

};

template <typename F>
CarFactoryImpl<F>::CarFactoryImpl(double a, double b, double bmax, double p,
    double a_stdev, double b_stdev, double c_stdev, double p_stdev, size_t seed, F func):
    CarFactory(p , p_stdev), rng_{std::mt19937(seed)},
    a_dist{a, a_stdev}, b_dist{b, b_stdev}, c_dist{bmax, c_stdev}, makeFollowModel_{func} {}

template <typename F>
Car CarFactoryImpl<F>::makeCar(double x0, double v0, double vdes, double t0) {
    double a = a_dist(rng_);
    double b = b_dist(rng_);
    double c = c_dist(rng_);
    double p = std::clamp<double>(politeness_dist_(rng_),0, 1);

    FollowModel m{makeFollowModel_(a, b, c, vdes), c, a, b, c, vdes};
    // Make a follow model, return a function that curries 
    return Car(carid_++, x0, v0, t0, p, m);
}

template <typename F>
Car CarFactoryImpl<F>::makeCar(size_t id, double x0, double v0, double vdes, double t0, double a, double b, double c, double p) {
    FollowModel m(makeFollowModel_(a, b, c, vdes));
    carid_ = std::max(carid_, id) + 1; // Ensure that the next car id is ALWAYS a new identifier
    return Car(id, x0, v0, t0, p, m);
}
